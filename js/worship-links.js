/**
 * Подписанные ссылки на снимки модуля «Поклонение».
 *
 * Бакет приватный: картинку показывает только ссылка с подписью и сроком.
 * Раньше её выписывали заново на каждом заходе — и браузер, видя новый
 * адрес, качал тот же снимок ещё раз: папка в сорок кадров приезжала
 * целиком при каждом возврате на страницу. Теперь ссылка живёт в
 * sessionStorage, пока до конца её срока больше десяти минут, и тот же
 * адрес достаётся из кэша браузера.
 *
 * Хранится в пределах вкладки и до её закрытия: на чужой компьютер
 * и в другую сессию ссылки не попадают.
 */
const WorshipLinks = (() => {
    const КЛЮЧ = 'worship_signed_v1';
    const ЗАПАС = 10 * 60 * 1000;        // моложе этого запаса ссылку не отдаём
    const ПРЕДЕЛ = 1500;                 // столько путей держим, остальное выкидываем

    const прочесть = () => {
        try { return JSON.parse(sessionStorage.getItem(КЛЮЧ) || '{}'); }
        catch { return {}; }
    };
    const записать = карта => {
        try { sessionStorage.setItem(КЛЮЧ, JSON.stringify(карта)); }
        catch { /* хранилище полно или закрыто — просто не запомним */ }
    };

    /** { путь: ссылка } для всех путей, у которых ссылка получилась. */
    async function подписать(db, пути, секунд = 3600) {
        const список = [...new Set((пути || []).filter(Boolean))];
        if (!список.length) return {};

        const сейчас = Date.now();
        const запомнено = прочесть();
        const итог = {};
        const нужно = [];
        список.forEach(п => {
            const з = запомнено[п];
            if (з && з.до - сейчас > ЗАПАС) итог[п] = з.u;
            else нужно.push(п);
        });

        if (нужно.length) {
            const { data, error } = await db.storage.from('worship').createSignedUrls(нужно, секунд);
            if (!error) {
                const до = Date.now() + секунд * 1000;
                (data || []).forEach(з => {
                    if (!з.signedUrl) return;
                    итог[з.path] = з.signedUrl;
                    запомнено[з.path] = { u: з.signedUrl, до };
                });
            }
            // просроченное выкидываем, а при переполнении — самое старое
            let строки = Object.entries(запомнено).filter(([, з]) => з.до > сейчас);
            if (строки.length > ПРЕДЕЛ) строки = строки.sort((a, b) => b[1].до - a[1].до).slice(0, ПРЕДЕЛ);
            записать(Object.fromEntries(строки));
        }
        return итог;
    }

    /** Одна ссылка — та же логика. */
    async function одна(db, путь, секунд = 3600) {
        return (await подписать(db, [путь], секунд))[путь] || '';
    }

    /** Снимок удалён или папка закрыта — его ссылку больше не раздаём. */
    function забыть(пути) {
        const запомнено = прочесть();
        [].concat(пути || []).forEach(п => delete запомнено[п]);
        записать(запомнено);
    }

    return { подписать, одна, забыть };
})();
