/**
 * Словарик алтарной. Новичок-волонтёр не знает, что такое мангала-арати
 * или шрингара, а стандарты написаны для тех, кто знает. Термин в тексте
 * стандарта подчёркнут пунктиром, по касанию — короткое пояснение;
 * на главной — весь список.
 *
 * Пояснения короткие и общие: подробности — в самих стандартах.
 * Править словарь — здесь (старший пуджари вычитывает формулировки).
 */
window.WorshipGlossary = (() => {
    const e = s => Layout.escapeHtml(s ?? '');

    // корень — чтобы ловить падежи: «арати», «арати», «бхоги», «бхогу»
    const СЛОВАРЬ = [
        { слово: 'Мангала-арати', корень: 'мангала[- ]арати', текст: 'Первая служба дня, перед рассветом: Божеств будят, предлагают лёгкое подношение и арати.' },
        { слово: 'Арати', корень: 'арати', текст: 'Поклонение с подношением светильника, благовоний, воды, ткани, цветов и опахала под пение.' },
        { слово: 'Бхога', корень: 'бхог', текст: 'Пища, приготовленная для подношения Божествам. После подношения она становится прасадом.' },
        { слово: 'Раджа-бхога', корень: 'раджа[- ]бхог', текст: 'Главное полуденное подношение пищи Божествам.' },
        { слово: 'Прасад', корень: 'прасад', текст: 'Освящённая пища — то, что осталось после подношения Божествам.' },
        { слово: 'Сандхья-арати', корень: 'сандхь[яи][- ]арати', текст: 'Вечерний арати, на закате.' },
        { слово: 'Шаяна-арати', корень: 'шаяна[- ]арати', текст: 'Последний арати дня, после которого Божества отходят ко сну.' },
        { слово: 'Гуру-пуджа', корень: 'гуру[- ]пудж', текст: 'Утреннее поклонение духовному учителю.' },
        { слово: 'Туласи', корень: 'туласи', текст: 'Священное растение, любимое Кришной. Ей поклоняются: обходят, поливают, предлагают арати; её листья кладут на подношения.' },
        { слово: 'Пуджари', корень: 'пуджари', текст: 'Тот, кто совершает поклонение Божествам в алтарной.' },
        { слово: 'Пуджа', корень: 'пудж(?!ари)', текст: 'Поклонение Божествам по установленному порядку.' },
        { слово: 'Шрингара', корень: 'шрингар', текст: 'Одевание и украшение Божеств.' },
        { слово: 'Абхишека', корень: 'абхишек', текст: 'Омовение Божеств — водой, молоком и другими нектарами; совершается по праздникам.' },
        { слово: 'Чарана-амрита', корень: 'чарана[- ]амрит', текст: 'Вода, которой омыли стопы Божеств; её принимают несколькими каплями.' },
        { слово: 'Ачамана', корень: 'ачаман', текст: 'Очищение водой перед служением: несколько глотков воды с произнесением имён Господа.' },
        { слово: 'Экадаши', корень: 'экадаши', текст: 'Одиннадцатый день лунного месяца, день поста от зерновых; в алтарной меняется подношение.' },
        { слово: 'Киртан', корень: 'киртан', текст: 'Пение святых имён; киртания — тот, кто ведёт пение во время службы.' },
        { слово: 'Гирлянда', корень: 'гирлянд', текст: 'Венок из цветов, который надевают на Божеств; его меняют по порядку, описанному в стандарте.' },
    ];

    // длинные первыми: «мангала-арати» раньше, чем «арати»
    const ПОРЯДОК = [...СЛОВАРЬ].sort((a, b) => b.корень.length - a.корень.length);

    /**
     * Подчёркивает первое упоминание каждого термина в контейнере.
     * Трогает только текстовые узлы вне ссылок, заголовков и кнопок.
     */
    function разметить(контейнер) {
        if (!контейнер) return;
        const уже = new Set();
        const обход = document.createTreeWalker(контейнер, NodeFilter.SHOW_TEXT, {
            acceptNode: узел => узел.parentElement?.closest('a, button, h1, h2, h3, code, .термин')
                ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
        });
        const узлы = [];
        while (обход.nextNode()) узлы.push(обход.currentNode);

        for (const узел of узлы) {
            for (const т of ПОРЯДОК) {
                if (уже.has(т.слово)) continue;
                const м = new RegExp(`(^|[^а-яё])(${т.корень}[а-яё]*)`, 'i').exec(узел.nodeValue);
                if (!м) continue;
                уже.add(т.слово);
                const начало = м.index + м[1].length;
                const хвост = узел.splitText(начало);
                хвост.splitText(м[2].length);
                const кнопка = document.createElement('button');
                кнопка.type = 'button';
                кнопка.className = 'термин';
                кнопка.dataset.термин = т.слово;
                кнопка.textContent = хвост.nodeValue;
                хвост.replaceWith(кнопка);
                break;                       // в этом узле дальше уже другие куски
            }
        }
    }

    let окошко = null;
    function показать(кнопка) {
        const т = СЛОВАРЬ.find(x => x.слово === кнопка.dataset.термин);
        if (!т) return;
        окошко?.remove();
        окошко = document.createElement('div');
        окошко.className = 'терминОкно';
        окошко.setAttribute('role', 'tooltip');
        окошко.innerHTML = `<b>${e(т.слово)}</b> — ${e(т.текст)}`;
        document.body.appendChild(окошко);
        const r = кнопка.getBoundingClientRect();
        const ширина = Math.min(320, innerWidth - 24);
        окошко.style.width = ширина + 'px';
        окошко.style.left = Math.max(12, Math.min(r.left + scrollX, scrollX + innerWidth - ширина - 12)) + 'px';
        окошко.style.top = (r.bottom + scrollY + 6) + 'px';
    }
    document.addEventListener('click', ev => {
        const кнопка = ev.target.closest('.термин');
        if (кнопка) { ev.preventDefault(); показать(кнопка); return; }
        if (!ev.target.closest('.терминОкно')) { окошко?.remove(); окошко = null; }
    });

    /** Весь словарик — окном: с главной, «что значат слова». */
    function окно() {
        let д = document.querySelector('#словарикОкно');
        if (!д) {
            д = document.createElement('dialog');
            д.id = 'словарикОкно';
            д.className = 'modal';
            д.innerHTML = `
                <div class="modal-box max-w-lg">
                    <h3 class="font-bold text-lg mb-1">Словарик алтарной</h3>
                    <p class="text-sm opacity-70 mb-3">Коротко о словах, которые встречаются в стандартах и расписании.</p>
                    <dl class="space-y-2">${[...СЛОВАРЬ].sort((a, b) => a.слово.localeCompare(b.слово, 'ru'))
                        .map(т => `<div><dt class="font-semibold">${e(т.слово)}</dt><dd class="text-sm opacity-80">${e(т.текст)}</dd></div>`).join('')}</dl>
                    <div class="modal-action"><form method="dialog"><button class="btn btn-sm">Понятно</button></form></div>
                </div>
                <form method="dialog" class="modal-backdrop"><button>закрыть</button></form>`;
            document.body.appendChild(д);
        }
        д.showModal();
    }

    return { разметить, окно, СЛОВАРЬ };
})();
