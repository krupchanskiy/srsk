/**
 * Общее для экранов магазина.
 *
 * Деньги и количества форматируются одинаково на всех семи экранах — иначе один
 * считает рупии до копеек, другой округляет, и отчёты расходятся на глаз.
 *
 * `ошибка()` существует потому, что молча проигнорированный отказ базы выглядит
 * на экране как «товара нет» или «долгов нет». Для склада и денег это опаснее,
 * чем честное сообщение об ошибке.
 */
const ShopUtils = (() => {
    const ЗНАК = { INR: '₹', RUB: '₽', USD: '$', EUR: '€' };

    // рупии считаем целыми (копеек в обороте нет), валюту — до центов
    const деньги = (n, вал = 'INR') =>
        new Intl.NumberFormat('ru-RU', { maximumFractionDigits: вал === 'USD' || вал === 'EUR' ? 2 : 0 })
            .format(Number(n) || 0) + ' ' + (ЗНАК[вал] || вал);

    // штуки бывают дробными: благовония и ткань продают на вес и метрами
    const штук = n => new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 3 })
        .format(Number(n) || 0);

    /**
     * Проверяет пачку ответов Supabase. Возвращает true, если была ошибка —
     * вызывающий код на этом останавливается и не рисует пустой экран.
     */
    function ошибка(результаты, что) {
        const плохой = (Array.isArray(результаты) ? результаты : [результаты])
            .find(р => р && р.error);
        if (!плохой) return false;
        Layout.handleError(плохой.error, что);
        return true;
    }

    // права на разметке, нарисованной после загрузки данных: статические элементы
    // auth-check обрабатывает сам, динамические — только по этому вызову
    const права = () => window.applyPermissions?.();

    const ПРИЧИНЫ_СПИСАНИЯ = { damage: 'Порча', loss: 'Утеря', gift: 'Подарок',
                               service: 'На служение', shortage: 'Недостача' };

    return { ЗНАК, деньги, штук, ошибка, права, ПРИЧИНЫ_СПИСАНИЯ };
})();
