-- Платежи за проживание было негде подтвердить.
--
-- Замечание Нитья-виласини (05.08.2026): бот прислал «Ждёт подтверждения»
-- по платежу Элиады Чигир на 17 280 ₽, в карточке сделки платёж виден,
-- а в «Предоплатах» его нет.
--
-- Причина: страница отбирала только `payment_type = 'org_fee'`, а этот
-- платёж — `accommodation`. Подтвердить платёж можно ТОЛЬКО на этой странице
-- (в карточке сделки кнопки нет), поэтому платежи за проживание висели
-- неподтверждёнными и не попадали в учёт: автопроводка в финмодуль идёт
-- по факту подтверждения, и в авансы при переезде они тоже не вошли.
--
-- Нашлось два таких платежа на 202 392 ₹, один — с 17 июня.
--
-- Правка в crm/prepayments.html: фильтр по типу снят, тип показан подписью
-- под суммой (для не-оргвзносов). Операции предоплат (перенос, возврат,
-- пожертвование) по-прежнему доступны только для подтверждённых оргвзносов —
-- эта логика жила отдельно и не менялась.

update translations set ru = 'Оргвзнос', en = 'Org fee', hi = 'शुल्क'
 where key = 'crm_payment_type_org_fee';

insert into translations (key, ru, en, hi, page) values
  ('crm_payment_type_accommodation', 'За проживание', 'Accommodation', 'आवास', 'CRM Предоплата')
on conflict (key) do update set ru = excluded.ru, en = excluded.en, hi = excluded.hi;
