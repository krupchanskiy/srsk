-- Объекты учёта «Магазин» и «Мурти Госвами» (тип project) и передача выручки казначею.
-- Применена на проде 16.10.2026.
--
-- Почему выручка попадает в журнал при сдаче денег, а не при закрытии смены:
-- финмодуль принципиально разрешает заводить доход только администратору финансов —
-- так устроена и автопроводка CRM, она просто пишет ошибку в лог, если прав нет.
-- Продавцу таких прав не дают, ослаблять это ради магазина нельзя. Зато физически
-- деньги переходят в кассу ашрама ровно в момент, когда продавец отдаёт их казначею:
-- тогда казначей своими правами доход и проводит. До этого деньги лежат в ящике,
-- и видно это на экране смены.
--
-- Таблицы: shop_handovers (пакет к сдаче) и shop_handover_lines (суммы по валютам
-- с разбивкой товары / свой выпуск / пожертвования). shop_shifts.handover_id
-- связывает сданные смены с пакетом.
