-- 274: папку в галерее снова можно создать.
-- Дату события из формы убрали (галерея — это папки со снимками, а не
-- наборы к дате), а в базе event_date осталась обязательной без значения
-- по умолчанию: создание падало с not-null. Поиск и подборки на неё
-- опираются, поэтому не снимаем обязательность, а подставляем день
-- создания по часам ашрама.
alter table worship_albums
    alter column event_date set default ((now() at time zone 'Asia/Kolkata')::date);
