-- «Папка», а не «набор»: в интерфейсе слово сменили по просьбе отдела
-- («это просто папки с картинками»), а сообщения базы, которые человек
-- видит при отказе, говорили по-старому. Меняются только тексты сообщений —
-- переписываем по живому определению функции, точными заменами строк.
do $$
declare
    замены text[][] := array[
        ['''Вести наборы может пуджари''', '''Вести папки со снимками может пуджари'''],
        ['''Набор не найден''', '''Папка не найдена'''],
        ['''Убрать набор в архив может тот, кто его завёл, или старший пуджари''',
         '''Убрать папку в архив может тот, кто её завёл, или старший пуджари'''],
        ['''Снимки из набора стоят в стандартах: %. Уберите их оттуда, иначе на их месте у всех будет пустота''',
         '''Снимки из папки стоят в стандартах: %. Уберите их оттуда, иначе на их месте у всех будет пустота'''],
        ['''Менять видимость набора может пуджари''', '''Менять видимость папки может пуджари'''],
        ['''Видимость меняет тот, кто загрузил набор, или старший пуджари''',
         '''Видимость меняет тот, кто завёл папку, или старший пуджари'''],
        ['''Снимки из набора стоят в стандартах: %. Закрыть набор — значит убрать их оттуда для всех, кроме отдела''',
         '''Снимки из папки стоят в стандартах: %. Закрыть папку — значит убрать их оттуда для всех, кроме отдела'''],
        ['''В подборке закрытый набор фотографий: % . Откройте его или уберите из подборки''',
         '''В подборке закрытая папка со снимками: %. Откройте её или уберите из подборки'''],
        ['''В тексте снимок из закрытого набора: %. Откройте набор или уберите снимок''',
         '''В тексте снимок из закрытой папки: %. Откройте папку или уберите снимок''']
    ];
    ф record;
    тело text;
    было text;
    i int;
begin
    for ф in select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
              where n.nspname = 'public'
                and p.proname in ('worship_album_update', 'worship_album_visibility',
                                  'worship_kit_grant', 'worship_version_images_open')
    loop
        тело := pg_get_functiondef(ф.oid);
        было := тело;
        for i in 1 .. array_length(замены, 1) loop
            тело := replace(тело, замены[i][1], замены[i][2]);
        end loop;
        if тело <> было then execute тело; end if;
    end loop;
end $$;
