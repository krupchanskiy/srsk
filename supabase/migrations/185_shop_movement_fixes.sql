-- F3. Приёмка СВОЕГО товара гасила чужую недостачу: владельца у неё нет, поэтому
--     строкам чеков проставлялось «ничего», долг не начислялся, а принятая партия
--     не вставала на полку — товар исчезал в момент приёмки, и настоящая поставка
--     владельца потом уже не находила, что гасить. Теперь свой выпуск недостачу не
--     гасит: партия встаёт на полку, минус схлопывается арифметически, а долг
--     начислится, когда придёт поставка владельца.
--     Проверено: продали 3 чужих мимо учёта → приняли 3 своих (остаток 0) →
--     пришла поставка владельца 3 по 60 → долг вырос ровно на 180 ₹.
