-- F9. В строку писалось «за чей счёт» не то, что выбрал оператор, а вывод из того,
--     вышла ли компенсация больше нуля. «Потеряли чужое за наш счёт, сумму
--     согласуем позже» навсегда записывалось как потеря владельца, и его претензия
--     пропадала. Теперь пишется выбор оператора; за счёт владельца компенсация
--     запрещена явной проверкой.
