-- F5. Списание считало доступное только по положительным партиям и не видело
--     непогашенную недостачу: при «5 на полке и −2 в минусе» можно было списать 5
--     и выставить владельцу счёт за две несуществующие штуки.
--     Проверено: списание 5 при реальных 3 отбивается.
