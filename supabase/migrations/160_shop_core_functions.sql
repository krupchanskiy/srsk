-- Модуль «Магазин», этап 3: ядро логики. Применена на проде 16.10.2026.
--
-- Представления:
--   shop_v_stock      — остаток по товару (может быть отрицательным: сигнал инвентаризации);
--   shop_v_owner_debt — долг владельцу: продано + компенсации потерь − возвраты − расчёты.
--
-- Функции (SECURITY DEFINER, право проверяется внутри):
--   shop_open_shift(float)        — открыть смену или вернуть уже открытую;
--   shop_post_sale(payload)       — провести чек;
--   shop_cancel_sale(id, reason)  — отменить чек, вернув товар в те же партии;
--   shop_receive_goods(payload)   — принять товар, создав поступление и партии;
--   shop_round_step(currency)     — шаг округления цены в валюте платежа.
--
-- Что важно в shop_post_sale:
--   * цены берутся из справочника, клиенту тут не доверяем;
--   * списание FIFO: сначала самые старые партии, строка чека хранит владельца
--     и цену расчёта именно той партии;
--   * если партий не хватило, продажа НЕ блокируется: товар лежал на полке, а в учёте
--     его не было. Недостача уходит в партию origin='shortfall', остаток становится
--     отрицательным и всплывает на инвентаризации;
--   * повторная отправка чека с тем же client_uid не создаёт дубль — это опора
--     офлайн-очереди кассы;
--   * сумма к оплате считается сервером: (товары − скидка) / курс, вверх до шага
--     округления валюты, плюс пожертвование.
--
-- Проверено прогонами в begin/rollback: две партии разных владельцев по 290 и 310,
-- продажа 4 шт → 3 по 290 первому, 1 по 310 второму, долги 870 и 310.
-- Продажа 3 шт при остатке 2 → строка из партии, строка shortfall, остаток −1.
-- Чек на 7500 ₹ со скидкой 500, рублями по курсу 0.95 → 7370 ₽, с даром 200 → 7570 ₽.
