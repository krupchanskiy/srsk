-- Флаг «участвует в кассе кафе» у ретрита (ВГ, сен 2026): часть ретритов —
-- внутренние проекты, которые ашрам финансирует сам (например, «Ретрит
-- Художников»), и к кассе кафе отношения не имеют. Выключенный флаг убирает
-- ретрит из подсказки ближайшего ретрита при вводе прихода/расхода кафе
-- (js/fin-utils.js, FinUtils.nearestRetreatObject).
alter table retreats add column cafe_eligible boolean not null default true;
comment on column retreats.cafe_eligible is 'Участвует ли ретрит в учёте кассы кафе (авто-подсказка ретрита для приходов/расходов кафе). Выключается для внутренних проектов, которые ашрам финансирует сам — например, «Ретрит Художников».';
