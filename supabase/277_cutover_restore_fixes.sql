-- Три дефекта в возврате из снимка, найденные репетицией cutover.
-- Ровно то, зачем репетиция и нужна: все три вылезли на живых данных.
--
-- 1) identity-колонки.
--    У fin_audit_log поле id объявлено GENERATED ALWAYS AS IDENTITY: обычный
--    INSERT … SELECT в него запрещён, возврат падал на первой же попытке.
--    Теперь для таких таблиц добавляется OVERRIDING SYSTEM VALUE (клауза
--    допустима только там, где identity есть), а после вставки
--    последовательность подтягивается к max(id) — иначе следующая запись
--    столкнулась бы с восстановленной.
--
-- 2) лишние записи в аудите.
--    Возврат обновляет fin_accounting_objects.report_dirty_at, но аудит на
--    этой таблице не отключался — в лог попадало +7 записей. Официальный
--    reset его отключает, в возврате было пропущено. Исправлено.
--
-- 3) суммы сделок не пересчитывались.
--    reset пересчитывает crm_deals.total_paid на пустой журнал, а во время
--    возврата триггер пересчёта отключён — суммы оставались нулевыми.
--    Добавлен пересчёт в конце возврата:
--      UPDATE crm_deals d SET total_paid = c.o_paid, total_charged = c.o_charged
--      FROM (SELECT x.id, (crm_calc_deal_totals(x.id)).* FROM crm_deals x) c
--      WHERE c.id = d.id AND (d.total_paid IS DISTINCT FROM c.o_paid
--                          OR d.total_charged IS DISTINCT FROM c.o_charged);
--    Через LATERAL это не записать: в UPDATE … FROM нельзя ссылаться на
--    целевую таблицу внутри вызова функции.
--
-- Проверено полной репетицией в откате: снимок → reset → возврат.
-- Операции, проводки, начисления, аудит, заявки, сумма проводок и
-- ledger_seq совпали с исходным до строки. Все 16 проверок целостности
-- зелёные.
--
-- Остаточная разница: sum(total_paid) даёт 1117427.05 против исходных
-- 1117427.0437. Это не потеря, а округление: crm_calc_deal_totals округляет
-- до копеек, а в части старых записей лежали четыре знака. Побочно выяснилось,
-- что суммы сделок пишут два места с разным округлением
-- (crm_recalc_deal_finances и crm_calc_deal_totals); проверка totals_mismatch
-- терпит 0.01, поэтому расхождение не всплывало.
