-- 605. Сброс общего пароля сотрудников у 5 суперпользователей (запись о разовой правке данных)
--
-- После миграции 472 (сброс общего пароля гостей) остался второй общий пароль —
-- у сотрудников. Решение ВГ 02.10: суперпользователям, кроме Сундары Рупы
-- (работает каждый день — ему окно-предупреждение на каждой странице),
-- поставить случайный пароль. Сессии не отзываем: кто вошёл — работает дальше,
-- при новом входе — «Забыли пароль?».
--
-- Выполнено на prod 2026-10-02 по конкретным id (5 строк).
update auth.users
   set encrypted_password = extensions.crypt(gen_random_uuid()::text || gen_random_uuid()::text, extensions.gen_salt('bf'))
 where id in ('61d7fda5-be84-42e7-a1c6-8dcf3c476056',  -- Мани Манджари деви даси
              '65d786b0-7dff-4c90-886e-413b39f77e3f',  -- Васудева Датта дас
              '2c94394f-f9a4-4bd2-a14d-a08936ac26dc',  -- Ранганатх дас
              '7cf9baeb-ba64-4a51-bb50-605b4347584e',  -- Кунджавасини деви даси
              '03549bcd-2d37-4b7b-978d-eb3279753df0'); -- Олег Карпов
