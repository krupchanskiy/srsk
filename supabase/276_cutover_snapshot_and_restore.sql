-- Снимок состояния перед cutover и возврат к нему.
--
-- Зачем: reset — единственное официально допустимое нарушение append-only,
-- и он необратим. PITR у проекта не включён (платный аддон), ежедневный
-- бэкап снимается около 05:05 по Мумбаи — то есть «до reset», но грубо:
-- откат потерял бы всю работу после снимка, включая CRM.
--
-- Этот снимок точнее и бесплатен: копирует ровно те 13 таблиц, которые
-- стирает fin_cutover_reset.sql, плюс значение боевой последовательности и
-- метки report_dirty_at. Возврат — обычный INSERT … SELECT, без внешних
-- инструментов и паролей.
--
-- Ограничение, о котором надо знать: снимок живёт в той же базе. Он спасает
-- от «reset прошёл, а данные оказались нужны», но НЕ от потери самой базы —
-- для этого остаётся ежедневный бэкап Supabase.
--
-- Три функции (полные тела — в базе):
--   fin_cutover_snapshot()        — создаёт схему cutover_snapshot
--   fin_cutover_snapshot_info()   — что в снимке и когда снят
--   fin_cutover_restore('ВОССТАНОВИТЬ ИЗ СНИМКА')
--
-- Возврат требует подтверждающей строки: он затирает текущее состояние.
-- Все три — только для fin_admin.
--
-- Актуальные определения:
--   SELECT pg_get_functiondef('fin_cutover_snapshot()'::regprocedure);
--   SELECT pg_get_functiondef('fin_cutover_restore(text)'::regprocedure);
