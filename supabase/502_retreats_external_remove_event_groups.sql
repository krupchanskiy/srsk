-- Упрощение модели «событий» (этап 2, пересмотр по итогам обсуждения с ВГ 22.09.2026):
-- среднее звено «Отдельное событие (сама группа)» у meal_groups оказалось лишним — реальная
-- причина отделять группу от общего «без события» — деньги (приход/расход, возможно проживание),
-- а это уже есть у ретрита. Вместо самостоятельного «события»-группы помечаем сам ретрит:
-- «наш» или «стороннее мероприятие» (is_external) — та же инфраструктура (финансы, заселение,
-- отчёты), просто с меткой. Данных на is_event/group_id не было (0 строк), сносим чисто.
alter table retreats add column is_external boolean not null default false;

-- вью events объединяла retreat:<id> и group:<id> (is_event); нигде в коде не использовалась
drop view events;

alter table meal_groups drop column is_event;
alter table residents drop column group_id;
