-- Будущий заезд не может быть «уже приехал».
--
-- Бэкфилл в 344 проставил arrived_at = check_in всем записям с именем —
-- включая тех, кто ещё только собирается. 18 человек (в том числе заезды
-- 18.08 и позже) числились приехавшими: в шахматке рисовались заселёнными
-- без кнопки «Заселить», в счёте кухни шли в свою категорию вместо
-- «ожидаемых», а бот про них молчал бы в день приезда.
--
-- Найдено тестом инвариантов 03.08.2026. Правим только след бэкфилла
-- (arrived_at ровно равен дате заезда) — ручные отметки не трогаем.

update residents
   set arrived_at = null
 where arrived_at is not null
   and check_in > current_date
   and arrived_at = check_in::timestamptz;
