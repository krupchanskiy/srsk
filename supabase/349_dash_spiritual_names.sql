-- Духовное имя «-» — это «имени нет», а не имя.
--
-- У девяти человек в справочнике spiritual_name = '-' (так заполняли анкету).
-- Все цепочки имён в приложении и сводках берут spiritual_name первым и
-- останавливаются на дефисе — люди показывались безымянными («-»), хотя
-- обычные имя-фамилия у всех есть. Замечено Адрианом 03.08.2026 в списке
-- «без комнат» Сева-ретрита.

update vaishnavas
   set spiritual_name = null
 where btrim(coalesce(spiritual_name, '')) = '-';
