-- 416. Платёж Адхиягьи дас: рубли записали как рупии
--
-- ВГ: «Адхиягья дас — 182 000 рублей был перевод на карту до переноса,
-- но не рупии, а рубли, это нужно поправить».
-- Курс на 17.06.2026 — 1.05 по справочнику fin_exchange_rates (1.15 действует
-- только с 22.07.2026). Сумму не трогаем: 182 520 — то, что ввели из выписки.
-- amount_inr пересчитает триггер crm_payments_calc_inr: 182 520 × 1.05 = 191 646 ₹.
update crm_payments set currency = 'RUB', rate_to_inr = 1.05
 where id = '2f10b084-1589-45d0-b8a3-7ae29352c017' and currency = 'INR';
