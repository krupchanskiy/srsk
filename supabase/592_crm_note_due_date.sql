-- 592: срок у заметки сделки — «принесёт до 30.03» (фаза 2, шаг 6, ВГ 27.09).
-- Заметку с договорённостью по оплате кассир пишет в карточке участника
-- (финмодуль), она уходит в историю сделки CRM. Срок нужен списку должников:
-- «обещал принести» (срок не прошёл) отличается от «забыл» (срок прошёл или
-- договорённости нет).

alter table crm_communications add column if not exists due_date date;

comment on column crm_communications.due_date is
  'Срок по договорённости (заметка кассира «принесёт до»), для списка должников финмодуля';
