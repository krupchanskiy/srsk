-- 472. Сброс общего пароля у 376 аккаунтов
--
-- Проверка ВГ показала: страница admin-create-accounts.html заводила всем
-- аккаунты с одним паролем 'rupaseva'. На 29.09.2026 он подходил к 376 из 422
-- живых аккаунтов, включая 7 суперпользователей и 12 человек с рабочими
-- ролями. Любой, кто знал чужую почту, входил под этим человеком.
--
-- Пароли заменены на случайные: вход по общему паролю невозможен, люди
-- восстанавливают доступ через «Забыли пароль». Письма к этому моменту
-- переведены на Resend и доходят во «Входящие», а не в спам.
--
-- Активные сессии намеренно НЕ отзываем — по решению Адриана, чтобы не
-- выбрасывать людей из системы посреди работы.
--
-- Фильтр encrypted_password like '$2%' нужен: у приглашённых аккаунтов
-- пароля нет вовсе, и crypt() на пустом значении падает с invalid salt.
update auth.users
   set encrypted_password = extensions.crypt(gen_random_uuid()::text || gen_random_uuid()::text,
                                             extensions.gen_salt('bf'))
 where deleted_at is null
   and encrypted_password like '$2%'
   and encrypted_password = extensions.crypt('rupaseva', encrypted_password);
