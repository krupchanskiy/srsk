-- Отметка фактического приезда, отдельно от имени.
--
-- Вопрос Адриана (02.08.2026): «А разве можно нажать „Заселить", если человек
-- ещё не заехал?» — нельзя. А до сих пор указать, кто именно приедет, можно
-- было только заселив: система отличала бронь от заселения по пустому имени.
-- Отсюда тупик: или знаем имя, но человек «уже живёт», или он «ожидается»,
-- но безымянный. И отсюда же двойной счёт на «Ретрите Художников» — бронь без
-- имени считалась отдельно от участника ретрита, хотя это один человек.
--
-- Теперь приезд — отдельный факт. Имя в брони можно указать заранее, а
-- «Заселить» ставит отметку. Статус записи не трогаем намеренно: по нему
-- фильтруют полтора десятка мест в коде, и правка каждого — риск молча
-- потерять броней из расчёта.

alter table residents add column if not exists arrived_at timestamptz;

comment on column residents.arrived_at is
  'Когда гость фактически заехал. NULL = ещё ожидается. Ставится кнопкой «Заселить».';

create index if not exists residents_arrived_idx on residents (arrived_at) where arrived_at is null;

-- Прошлые записи: всё, где имя уже проставлено, — состоявшиеся заселения.
-- Брони без имени остаются ожидаемыми, как и были.
update residents
   set arrived_at = check_in::timestamptz
 where arrived_at is null
   and (vaishnava_id is not null or coalesce(btrim(guest_name), '') <> '')
   and status in ('confirmed', 'checked_out');
