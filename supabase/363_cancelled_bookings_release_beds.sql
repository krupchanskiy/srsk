-- Отменённые брони держали занятые места: при отмене одного места из групповой брони
-- шахматка помечала отменённой всю бронь, но снимала только одну запись.
-- Логика в js/pages/timeline.js исправлена; здесь приводим данные в соответствие статусу брони.
-- Затрагивает 3 записи: Чандра-рекха дд (Гостевой дом №2, 12.08–08.09, шла в счёт питания)
-- и два места Бхакти Чайтанья Свами (Коттедж 1 №4, 01–10.10, давали 4 человек на 2 места).
update residents res
   set status = 'cancelled'
  from bookings bk
 where bk.id = res.booking_id
   and bk.status = 'cancelled'
   and res.status = 'confirmed';
